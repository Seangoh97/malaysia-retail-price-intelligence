args<-commandArgs(TRUE)
if(length(args)!=2) stop('Usage: Rscript scripts/score.R quotes.csv scored.csv',call.=FALSE)
source('R/core.R')
assert(file.exists('results/model.rds'),'Run scripts/run.R first')
q<-readr::read_csv(args[1],show_col_types=FALSE)
assert(nrow(readr::problems(q))==0,'Quote CSV parsing failures')
assert(!any(c('item','unit','group') %in% names(q)),'Quote CSV must not include item/unit/group metadata; use model lookup')
b<-readRDS('results/model.rds')
readr::write_csv(benchmark(b,q),args[2])
cat('Compared',nrow(q),'quotes against',b$month,'historical benchmarks.\n')
